import assert from 'node:assert/strict';
import {unit,centroid,ranked,pca,normalizePoints,locate,parseGenerated} from '../semantic-math.js';
const a=unit([2,0,0]),b=unit([0,2,0]),c=unit([.9,.1,0]);
const records=[{key:'home',vector:a},{key:'music',vector:b},{key:'family',vector:c}];
assert.equal(ranked(a,records,'home')[0].key,'family');
assert.equal(ranked(b,records,'music')[0].key,'family');
assert.deepEqual(centroid([a,a]),a);
const points=normalizePoints(pca([a,b,c]));
assert(points.flat().every(Number.isFinite));
assert(points.flat().every(v=>v>=0&&v<=1));
const positions={home:[.1,.2],music:[.9,.8],family:[.2,.2]};
assert.deepEqual(locate(a,records,positions),positions.home);
assert(locate(unit([.95,.05,0]),records,positions)[0]<.3);
assert(locate(unit([.05,.95,0]),records,positions)[0]>.7);
assert.deepEqual(normalizePoints(pca([a,a,a])),[[.5,.5],[.5,.5],[.5,.5]]);
assert.deepEqual(pca([]),[]);
const rows=Array.from({length:20},(_,i)=>({name:`Fixture ${i}`,memory:`Test memory ${i}`}));
assert.equal(parseGenerated({output:['```json\n',JSON.stringify(rows),'\n```']}).length,20);
assert.throws(()=>parseGenerated({output:'blocked by allowlist'}));
assert.throws(()=>parseGenerated({output:'[]'}));
assert.throws(()=>parseGenerated({output:JSON.stringify(rows.map(()=>({name:'x'})))}));
console.log('PASS semantic rankings, interpolation, PCA edge cases, synthetic response validation');
